const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const {pathToFileURL}=require('url');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'../09-设计与原型/17-订单履约时效管理原型');
const target=path.join(root,'发货时效预警策略.html');
const before=fs.readFileSync(path.join(__dirname,'sla-before-source.html'),'utf8');
const after=fs.readFileSync(target,'utf8');
assert.equal(after.replace('<link rel="stylesheet" href="发货预警页面.css?v=1">',''),before);
console.log('PASS: original HTML and all scripts unchanged except stylesheet reference');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(target).href);
 const initial=await page.locator('#inlineOrderDetails .oms-order').count();assert(initial>0);
 await page.locator('.clarity-metrics .metric.danger').click();
 assert.equal(await page.locator('#inlineOrderDetails .oms-order').count(),8);
 await page.locator('.workflow-five .stage').nth(1).click();
 assert.match(await page.locator('#inlineOrderDetails .overview-head').innerText(),/发货/);
 await page.locator('.clarity-metrics .metric').first().click();
 await page.locator('#orderQueryNo').fill('NO-SUCH-ORDER');
 await page.locator('.order-search button[type=submit]').click();
 assert.equal(await page.locator('#inlineOrderDetails .oms-order').count(),0);
 assert(await page.locator('.empty-orders').isVisible());
 await page.getByRole('button',{name:'清空查询',exact:true}).click();
 assert.equal(await page.locator('#inlineOrderDetails .oms-order').count(),initial);
 await page.locator('#inlineOrderDetails .oms-order').first().getByRole('button',{name:/订单详情/}).click();
 assert(await page.locator('#orderDialog').isVisible());
 await page.locator('#orderDialog').getByRole('button',{name:/关闭/}).first().click();
 await page.getByRole('button',{name:'系统客户订单',exact:true}).click();
 assert(await page.locator('#overviewSurface').isVisible());
 await page.getByRole('button',{name:'全部订单',exact:true}).click();
 for(const width of [1440,1280,1024,768,390]){
  await page.setViewportSize({width,height:1000});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`page overflow at ${width}`);
  assert(await page.locator('.workflow-five').evaluate(e=>e.scrollWidth<=e.clientWidth+1),`clipped workflow at ${width}`);
 }
 await page.setViewportSize({width:1440,height:1000});
 await page.getByRole('link',{name:'订单列表',exact:true}).click();
 await page.getByRole('button',{name:/经销.*KA下单/}).first().click();
 assert(await page.locator('#kaDrawer').isVisible());
 await page.getByRole('button',{name:'关闭下单',exact:true}).click();
 await page.getByRole('link',{name:'订单接单列表',exact:true}).click();
 assert.match(await page.locator('.page-head h1').innerText(),/接单/);
 await page.screenshot({path:path.join(__dirname,'sla-acceptance-after.png')});
 await page.getByRole('link',{name:'履约总览',exact:true}).click();
 await page.screenshot({path:path.join(__dirname,'sla-after.png')});
 assert.deepEqual(errors,[]);
 console.log('PASS: metric/node/customer filters, search/empty/reset, order detail, new-order drawer, acceptance navigation; five viewport widths; no browser runtime errors');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
