def uid():
    return uuid.uuid4().hex[:22]

def topic(title, children=None):
    node = {"id": uid(), "class": "topic", "title": title}
    if children:
        node["children"] = {"attached": children}
    return node

def convert(title, value):
    if isinstance(value, dict):
        return topic(title, [convert(k, v) for k, v in value.items()])
    return topic(title, [topic(str(x)) for x in value])

